/**
 * Export — the ingenuity hook. The brain ships as plain markdown files that
 * agents already read. No API, no server, no lock-in: `git clone` is the
 * export. Every file is generated from the founder's own answers.
 */

const line = (s) => String(s ?? '').trim()
const today = () => new Date().toISOString().slice(0, 10)

export const AGENTS_SNIPPET = `## Business context — read before acting

Before acting on anything business-shaped (pricing, positioning, features,
naming, marketing, "should we..."), read business-brain/:

- business-brain/charter.md — what this is and who it is for
- business-brain/business-model.md — the model verdict and its reasoning
- business-brain/gaps.md — what is still undecided, ranked
- business-brain/decisions.md — recorded decisions; these are SETTLED unless
  the founder says otherwise

Our words mean what business-brain/glossary.md says. When you learn something
business-shaped in a session, append it to business-brain/decisions.md with a
one-line rationale — the brain only compounds if sessions write back.`

export function buildBrainFiles({ report, answers, repo, profile }) {
  const v = report?.verdict ?? {}
  const rules = report?.rules ?? { results: [], gaps: [] }
  const sc = report?.scenarios ?? {}
  const name = repo?.name ?? line(profile?.name) ?? 'this project'

  const files = {}

  files['business-brain/README.md'] = `# business-brain/

Business context for ${name}, in plain markdown — generated by Bearing
(open source, MIT) on ${today()} from the founder's own answers.

This folder is the interface: agents that read files (Claude Code, Cursor,
Codex, anything with a rules file) can load it. Edit freely — it is yours.
Nothing here is stored anywhere else.

Reading order: charter → business-model → gaps → decisions.
`

  files['business-brain/charter.md'] = `# Charter

**What this is:** ${line(answers.p1) || '(not recorded)'}

**Who pays:** ${line(answers.b3) || '(not recorded — see gaps.md)'}

**Stage:** ${line(answers.u1) || '(not recorded)'}
${answers.a1 ? `\n**Provenance:** how much of the codebase agents wrote: ${answers.a1} — context files are load-bearing here.\n` : ''}`

  const tells = (v.trace ?? [])
    .sort((a, b) => b.weight - a.weight)
    .slice(0, 5)
    .map((t) => `- You said "${t.answer}" → ${t.model} (+${t.weight})`)
    .join('\n')

  files['business-brain/business-model.md'] = `# Business model

**Verdict:** ${v.label ?? 'not enough signal'} · confidence ${v.confidence ?? 'n/a'} · ruleset ${v.doctrine_version ?? ''}

${line(report?.why)}

## The tells (your words, weighed)

${tells || '- (none recorded)'}

## Alternatives considered

${(v.alternatives ?? []).map((a) => `- ${a.label} (score ${a.score})`).join('\n') || '- (none)'}

## Assumptions to validate

${(report?.assumptions ?? []).map((a, i) => `${i + 1}. ${a}`).join('\n') || '(none)'}
`

  files['business-brain/customers.md'] = `# Customers & evidence

**Who uses it today:** ${line(answers.u1) || '(not recorded)'}

**Strongest evidence someone wants this:**
> ${line(answers.u3) || '(not recorded)'}

**Month-12 expectation:** ${answers.u2 || '?'} users/transactions per month at ~$${answers.b4 || '?'} — a founder guess, marked as one.

| Scenario | M12 ARR |
| --- | --- |
| Conservative | $${(sc.conservative?.m12_arr ?? 0).toLocaleString('en-US')} |
| Base | $${(sc.base?.m12_arr ?? 0).toLocaleString('en-US')} |
| Optimistic | $${(sc.optimistic?.m12_arr ?? 0).toLocaleString('en-US')} |

Growth assumption: ${answers.b5 || '?'}% month-over-month (named so it can be tested).
`

  files['business-brain/stack.md'] = `# Stack

${repo ? `**Repo:** ${repo.name} — ${line(repo.description) || 'no description'}
**Language:** ${repo.language || 'unknown'} · **Stars:** ${repo.stars ?? 0}
**Agent context files found:** ${repo.agentFiles?.length ? repo.agentFiles.join(', ') : 'none'}
**AI dependencies:** ${repo.aiDeps?.length ? repo.aiDeps.join(', ') : 'none detected'}
**License file:** ${repo.hasLicense ? 'yes' : 'MISSING'}
${repo.source !== 'github' ? '\n> Note: these signals come from the bundled demo fixture, not a live fetch.\n' : ''}` : 'No repo connected at intake time.'}

**Agents & tools in the loop (founder-reported):** ${line(answers.a3) || '(not recorded)'}

**Where business context lived before this folder:** ${line(answers.a2) || '(not recorded)'}
`

  files['business-brain/gaps.md'] = `# Gaps — what is still undecided, ranked

Statuses from the Bearing dev-readiness ruleset (${v.doctrine_version ?? 'devrules-v0'}).
Rank and reason, never a score. Fix them by making the decision and recording
it in decisions.md — not by editing this file.

${rules.results
    .map((r) => `## ${r.id} — ${r.name}\n- **Status:** ${r.status}\n- **Reason:** ${r.reason}\n- **Why it matters:** ${r.rationale}`)
    .join('\n\n')}
`

  files['business-brain/decisions.md'] = `# Decisions

Recorded decisions are settled unless the founder says otherwise. Append,
never delete — supersede with a new entry.

## D-0001 — Adopted a business brain (${today()})
The business context for ${name} lives in business-brain/ as plain markdown,
readable by every agent in the stack. Sessions that learn something
business-shaped write it back here.
`

  files['business-brain/glossary.md'] = `# Glossary

Our words mean what this file says. Add terms as they earn definitions.

- **business brain** — this folder: the business context agents load.
- **gap** — a decision not yet made, named in gaps.md with a reason.
- **settled** — recorded in decisions.md; agents treat it as fixed until superseded.
`

  files['AGENTS.md (snippet)'] = AGENTS_SNIPPET

  return files
}
